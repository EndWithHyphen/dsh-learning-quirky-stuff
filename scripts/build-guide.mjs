import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { VERSION } from '../shared/version.js';

export async function buildGuide() {
  const source = await readFile(new URL('../docs/user-guide.html', import.meta.url), 'utf8');
  const chapters = [...source.matchAll(/<section class="chapter" id="([a-z-]+)">\s*<h2>([^<]+)<\/h2>/g)];
  const sections = [...source.matchAll(/<section class="chapter" id="([a-z-]+)">/g)];
  if (
    !chapters.length ||
    chapters.length !== sections.length ||
    new Set(chapters.map((chapter) => chapter[1])).size !== chapters.length ||
    chapters.some((chapter, index) => Number(chapter[2].match(/^\d+/)?.[0]) !== index + 1)
  )
    throw new Error('使用说明的章节编号或目录结构不完整');
  const contents = chapters.map(([, id, title]) => `<a href="#${id}">${title}</a>`).join('\n');
  const html = source.replace('<!-- CONTENTS -->', contents).replaceAll('__STUDYBOARD_VERSION__', VERSION);
  await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
  await writeFile(
    new URL('../src/generated/user-guide.js', import.meta.url),
    '// Generated by scripts/build-guide.mjs from docs/user-guide.html.\nexport default ' +
      JSON.stringify(html) +
      ';\n',
  );
  await writeFile(new URL('../chrome-extension/help.html', import.meta.url), html);
}
